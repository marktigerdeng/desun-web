    function getPageKey() {
        var p = location.pathname.split('/').pop() || 'index.html';
        return p.replace('.html', '') || 'index';
    }

    function getLang() { return localStorage.getItem('desun_lang') || '繁'; }
    function setLang(l) { localStorage.setItem('desun_lang', l); }

    function applyLang(lang) {
        var dict = T[lang];
        if (!dict) return;
        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            var k = el.getAttribute('data-i18n');
            if (dict[k] != null) el.textContent = dict[k];
        });
        document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
            var k = el.getAttribute('data-i18n-html');
            if (dict[k] != null) el.innerHTML = dict[k];
        });
        var pk = getPageKey();
        if (TITLES[pk] && TITLES[pk][lang]) document.title = TITLES[pk][lang];
        var lm = { '繁': 'zh-Hant', '简': 'zh-Hans', 'EN': 'en' };
        document.documentElement.lang = lm[lang] || 'zh-Hant';
        document.querySelectorAll('.lang-switcher span:not(.lang-divider)').forEach(function (s) {
            s.classList.toggle('lang-active', s.textContent.trim() === lang);
        });
        window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));
    }

    // Expose for other scripts
    window.desunI18n = { getLang: getLang, applyLang: applyLang };

    var saved = getLang();
    document.querySelectorAll('.lang-switcher span:not(.lang-divider)').forEach(function (span) {
        span.style.cursor = 'pointer';
        span.addEventListener('click', function () {
            var lang = span.textContent.trim();
            setLang(lang);
            applyLang(lang);
        });
    });
    applyLang(saved);
